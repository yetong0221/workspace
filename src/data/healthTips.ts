/**
 * 根据当天日期返回一条健康贴士（每天自动轮播）
 */
export function getTodayHealthTip(): HealthTip {
  const today = new Date()
  // 使用年份+天数组合保证每天不同
  const seed = today.getFullYear() * 1000 + Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) / 86400000
  )
  // 伪随机洗牌：用种子的奇偶性来决定起始偏移
  const offset = (seed * 7 + 3) % healthTips.length
  return healthTips[offset]
}
